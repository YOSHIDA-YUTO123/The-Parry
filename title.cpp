//===================================================
// 更新処理
//===================================================
void CTitle::Update(void)
{
	// キーボードの取得
	CInputKeyboard* pKeyboard = CManager::GetInputKeyboard();

	if (pKeyboard->GetTrigger(DIK_F9))
	{
		// 新しいモードの設定
		CManager::SetMode(new CGame);
	}
}

