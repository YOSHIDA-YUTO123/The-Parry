#include "Observer.h"
#include"Gage.h"

//===================================================
// コンストラクタ
//===================================================
CObserver::CObserver()
{
}

//===================================================
// デストラクタ
//===================================================
CObserver::~CObserver()
{
}

//===================================================
// コンストラクタ
//===================================================
CHpObserver::CHpObserver(CHpGage* pHpGage)
{
	m_pHpGage = pHpGage;
}

//===================================================
// デストラクタ
//===================================================
CHpObserver::~CHpObserver()
{
}

//===================================================
// 通知処理
//===================================================
void CHpObserver::OnNotify(const int nValue)
{
	if (m_pHpGage != nullptr)
	{
		// HPの設定処理
		m_pHpGage->SetHp(nValue);
	}
}
